REGIONS = ["NA", "EU"]

PINNED = set(TEAMS)                       # hand-maintained, never overwritten
ROSTERS_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "rosters.json")


def _load_rosters(path=ROSTERS_FILE):
    """Merge build_rosters.py output into TEAMS. Missing file is fine."""
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {}

    loaded = {}
    for name, info in (data.get("teams") or {}).items():
        players = {k: int(v) for k, v in (info.get("players") or {}).items()}
        if not players or name in PINNED:
            continue
        loaded[name] = {
            "region": info.get("region") or "",
            "division": info.get("division") or "",
            "team_id": info.get("team_id") or 0,
            "roles": info.get("roles") or {},
            "players": players,
        }
    TEAMS.update(loaded)
    return loaded


