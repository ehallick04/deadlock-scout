def divisions():
    """Division names present in the loaded rosters, in league order."""
    seen = []
    for info in TEAMS.values():
        d = info.get("division")
        if d and d not in seen:
            seen.append(d)
    return sorted(seen)


def teams_in(division):
    return [n for n, t in TEAMS.items() if t.get("division") == division]


def search(query, limit=50):
    """Whitespace-insensitive substring match over team names."""
    q = "".join((query or "").lower().split())
    if not q:
        return sorted(TEAMS, key=str.lower)[:limit]
    hits = [n for n in TEAMS if q in "".join(n.lower().split())]
    return sorted(hits, key=str.lower)[:limit]


def info(name):
    """Everything known about one team."""
    t = TEAMS.get(name)
    if not t:
        return None
    return {"team": name, "region": t.get("region", ""),
            "division": t.get("division", ""), "team_id": t.get("team_id", 0),
            "pinned": name in PINNED, "players": dict(t["players"]),
            "roles": dict(t.get("roles") or {})}


def team_names(region=None):
    """Team names, optionally just one region's."""
    return [name for name, t in TEAMS.items()
            if region is None or t["region"] == region]


def roster(selection):
    """
    selection: a team name, a region ("NA" / "EU"), or "All".
    -> (list of account_ids, {account_id: {"ign":..., "team":..., "region":...}})
    """
    if selection == "All":
        names = team_names()
    elif selection == "All (pinned)":
        names = sorted(PINNED, key=str.lower)
    elif selection in REGIONS:
        names = team_names(selection)
    elif selection in TEAMS:
        names = [selection]
    elif teams_in(selection):
        names = sorted(teams_in(selection), key=str.lower)
    else:
        raise ValueError(f"unknown selection: {selection!r}")

    ids, labels = [], {}
    for team in names:
        entry = TEAMS[team]
        for ign, account_id in entry["players"].items():
            ids.append(account_id)
            labels[account_id] = {"ign": ign, "team": team,
                                  "region": entry.get("region", ""),
                                  "division": entry.get("division", "")}
    return ids, labels


def roster_many(selections):
    """
    Combine several selections into one roster.
    selections: any mix of team names, regions, and "All".
    -> (ids, {account_id: {"ign","team","region"}})
    """
    ids, labels = [], {}
    for name in selections:
        got_ids, got_labels = roster(name)
        for account_id in got_ids:
            if account_id not in labels:
                ids.append(account_id)
            labels[account_id] = got_labels[account_id]
    return ids, labels


def choices(include_league=False):
    """
    Everything you can pick, in menu order. The league teams are left out
    unless asked for -- 180 entries do not belong in a menu; use search().
    """
    pinned = sorted(PINNED, key=str.lower)
    if not include_league:
        return ["All (pinned)", *REGIONS, *pinned]
    return ["All", "All (pinned)", *REGIONS, *divisions(),
            *sorted(TEAMS, key=str.lower)]


def find_player(account_id):
    """
    Is this account on any roster? -> {"ign", "team", "region"} or None.
    Used to recognise a sub who is themselves a pro on another team.
    """
    for team in list(PINNED) + [t for t in TEAMS if t not in PINNED]:
        entry = TEAMS[team]
        for ign, aid in entry["players"].items():
            if aid == account_id:
                return {"ign": ign, "team": team,
                        "region": entry.get("region", ""),
                        "division": entry.get("division", "")}
    return None
